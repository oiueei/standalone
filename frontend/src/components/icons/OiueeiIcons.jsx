import { IconCamera } from 'hds-react';

/**
 * OIUEEI's own icons, the ones `hds-react` does not have. They are used exactly like
 * the HDS ones — `<IconGeneral aria-hidden="true" />` — and wear the same classes, so
 * the CSS that reaches an HDS icon reaches these.
 *
 * The classes are not copied: they come from rendering a real HDS icon of the same
 * size (a plain function component), so an HDS upgrade that renames them takes ours
 * along. The sizes are HDS's (`xs` 16, `s` 24, `m` 32, `l` 48, `xl` 64), written
 * either short or as HDS's own names (`extraSmall`, `small`, …). Default `s`.
 * Each icon is `currentColor`, and, as in HDS, decorative (`aria-hidden`) unless told
 * otherwise.
 */

const SIZE_KEYS = {
  xs: 'xs',
  extraSmall: 'xs',
  s: 's',
  small: 's',
  m: 'm',
  medium: 'm',
  l: 'l',
  large: 'l',
  xl: 'xl',
  extraLarge: 'xl',
};

const HDS_SIZE = {
  xs: 'extraSmall',
  s: 'small',
  m: 'medium',
  l: 'large',
  xl: 'extraLarge',
};

/** The size key an icon draws at; an unknown value falls back to the default, `s`. */
const sizeKey = (size) => SIZE_KEYS[size] ?? 's';

/** The classes HDS puts on an icon of this size, read off a real one. */
const hdsClasses = (key) => IconCamera({ size: HDS_SIZE[key] }).props.className;

function makeIcon(name, label, paths) {
  const Icon = ({
    'aria-label': ariaLabel = label,
    'aria-hidden': ariaHidden = true,
    className = '',
    color,
    size,
    style = {},
    ...rest
  }) => {
    const key = sizeKey(size);
    const { viewBox, shapes } = typeof paths === 'function' ? paths(key) : paths;
    return (
      <svg
        aria-label={ariaLabel}
        aria-hidden={ariaHidden}
        className={[hdsClasses(key), className].filter(Boolean).join(' ')}
        role="img"
        xmlns="http://www.w3.org/2000/svg"
        viewBox={viewBox}
        color={color}
        style={style}
        {...rest}
      >
        {shapes.map((d) => (
          <path key={d} d={d} fillRule="evenodd" clipRule="evenodd" fill="currentColor" />
        ))}
      </svg>
    );
  };
  Icon.displayName = name;
  return Icon;
}

